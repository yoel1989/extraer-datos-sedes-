-- Función para obtener resumen financiero
CREATE OR REPLACE FUNCTION resumen_financiero()
RETURNS TABLE(
    total_ingresos NUMERIC,
    total_egresos NUMERIC,
    balance NUMERIC,
    total_transacciones BIGINT
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        COALESCE(SUM(CASE WHEN tipo = 'ingreso' THEN monto ELSE 0 END), 0) as total_ingresos,
        COALESCE(SUM(CASE WHEN tipo = 'egreso' THEN monto ELSE 0 END), 0) as total_egresos,
        COALESCE(SUM(CASE WHEN tipo = 'ingreso' THEN monto ELSE -monto END), 0) as balance,
        COUNT(*) as total_transacciones
    FROM transacciones;
END;
$$ LANGUAGE plpgsql;

-- Función para obtener evolución mensual
CREATE OR REPLACE FUNCTION evolucion_mual(meses INTEGER DEFAULT 6)
RETURNS TABLE(
    mes VARCHAR(7),
    ingresos NUMERIC,
    egresos NUMERIC,
    balance NUMERIC
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        TO_CHAR(fecha, 'YYYY-MM') as mes,
        COALESCE(SUM(CASE WHEN tipo = 'ingreso' THEN monto ELSE 0 END), 0) as ingresos,
        COALESCE(SUM(CASE WHEN tipo = 'egreso' THEN monto ELSE 0 END), 0) as egresos,
        COALESCE(SUM(CASE WHEN tipo = 'ingreso' THEN monto ELSE -monto END), 0) as balance
    FROM transacciones
    WHERE fecha >= CURRENT_DATE - INTERVAL '1 month' * meses
    GROUP BY TO_CHAR(fecha, 'YYYY-MM')
    ORDER BY mes;
END;
$$ LANGUAGE plpgsql;