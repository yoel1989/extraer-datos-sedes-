-- =============================================
-- Triggers para actualizar timestamps
-- =============================================

-- Trigger para actualizar actualizado_en en users
CREATE OR REPLACE FUNCTION actualizar_timestamp_users()
RETURNS TRIGGER AS $$
BEGIN
    NEW.actualizado_en = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_actualizar_users
    BEFORE UPDATE ON users
    FOR EACH ROW
    EXECUTE FUNCTION actualizar_timestamp_users();

-- Trigger para actualizar actualizado_en en transacciones
CREATE OR REPLACE FUNCTION actualizar_timestamp_transacciones()
RETURNS TRIGGER AS $$
BEGIN
    NEW.actualizado_en = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_actualizar_transacciones
    BEFORE UPDATE ON transacciones
    FOR EACH ROW
    EXECUTE FUNCTION actualizar_timestamp_transacciones();

