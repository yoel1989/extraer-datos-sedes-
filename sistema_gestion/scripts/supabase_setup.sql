-- =============================================
-- Script de creación de tablas para Supabase
-- Sistema de Gestión Integral
-- =============================================

-- 1. Tabla de usuarios (autenticación)
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) UNIQUE NOT NULL,
    email VARCHAR(120) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    rol VARCHAR(20) DEFAULT 'usuario' CHECK (rol IN ('admin', 'usuario')),
    activo BOOLEAN DEFAULT true,
    ultimo_login TIMESTAMP WITH TIME ZONE,
    creado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 2. Tabla de extracciones de datos
CREATE TABLE IF NOT EXISTS extractions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sitio VARCHAR(50) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    archivo_pdf VARCHAR(255),
    total_ventas INTEGER DEFAULT 0,
    total_valor INTEGER DEFAULT 0,
    total_comision INTEGER DEFAULT 0,
    total_enviar INTEGER DEFAULT 0,
    estado VARCHAR(20) DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'en_progreso', 'completado', 'error')),
    creado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    completado_en TIMESTAMP WITH TIME ZONE
);

-- 3. Tabla de logs de extracciones
CREATE TABLE IF NOT EXISTS extraction_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    extraction_id BIGINT REFERENCES extractions(id) ON DELETE CASCADE,
    mensaje TEXT NOT NULL,
    tipo VARCHAR(20) DEFAULT 'info' CHECK (tipo IN ('info', 'warning', 'error', 'success')),
    creado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 4. Tabla de categorías contables
CREATE TABLE IF NOT EXISTS categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) UNIQUE NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('ingreso', 'egreso')),
    color VARCHAR(7) DEFAULT '#007bff',
    creado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 5. Tabla de transacciones financieras
CREATE TABLE IF NOT EXISTS transacciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('ingreso', 'egreso')),
    categoria VARCHAR(100) NOT NULL,
    descripcion TEXT,
    monto NUMERIC(15,2) NOT NULL,
    referencia VARCHAR(50), -- ID de extracción relacionada
    fecha DATE NOT NULL,
    creado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    
    -- Foreign key a categorías (opcional para mayor flexibilidad)
    CONSTRAINT fk_transacciones_categoria 
        FOREIGN KEY (categoria) REFERENCES categorias(nombre) 
        ON UPDATE CASCADE
);

